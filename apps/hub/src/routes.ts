/** Composition of every module's HTTP routes (ADR-0020). */
export function registerRoutes(app: FastifyInstance, deps: RouteDeps): void {
  const ctx = createRouteContext(deps);
  registerSystemRoutes(app, ctx);
  registerHarnessRoutes(app, ctx);
  registerPromptsRoutes(app, ctx);
  registerWorkspaceRoutes(app, ctx);
  registerMainSyncSettingsRoutes(app, ctx);
  registerProjectCreateRoute(app, ctx);
  registerSessionsRoutes(app, ctx);
  registerCompactionSettingsRoutes(app, ctx);
  registerDiscoveryRoutes(app, ctx);
  registerNotificationsRoutes(app, ctx);
  registerRunsRoutes(app, ctx);
  registerHandoverRoutes(app, ctx);
  registerIdentityRoutes(app, ctx);
  registerApprovalsRoutes(app, ctx);
  registerSearchRoutes(app, ctx);
  registerCodeRoutes(app, ctx);
  registerGraphRoutes(app, ctx);
  registerGitGraphRoutes(app, ctx);
  registerReleaseNotesRoutes(app, ctx);
  registerVaultRoutes(app, ctx);
  registerSwarmRoutes(app, ctx);
  registerTeamPairingRoutes(app, ctx);
  registerFactoryRoutes(app, ctx);
  registerCommandRoutes(app, ctx, deps.assistantModel ? { model: deps.assistantModel } : {});
  registerReviewsRoutes(app, ctx);
  registerForgeRoutes(app, ctx);
  registerAutomationsRoutes(app, ctx);
  registerBrowserRoutes(app, ctx);
  registerDeviceRoutes(app, ctx);
  registerClientReportRoutes(app, ctx);

  registerAiMetricsRoutes(app, ctx);
  registerHostMetricsRoutes(app, ctx);
  registerInferenceRoutes(app, ctx);
  registerStatisticsRoutes(app, ctx);
  registerConnectionRoutes(app, ctx);
  registerKnowledgeRoutes(app, ctx);
  registerScanRoutes(app, ctx);
}
